  SELECT z.content_version_id, z.id, (e->>'speciesId')::int AS species_id,
    (e->>'formId')::int AS form_id, sum((e->>'weight')::numeric) AS weight
  FROM "zones" z CROSS JOIN LATERAL jsonb_array_elements(z.encounters) e
  GROUP BY 1, 2, 3, 4
),
type_stats AS (
  SELECT p.content_version_id, p.id, t.type, count(*) AS n, sum(p.weight) AS weight
  FROM pokemon p
  LEFT JOIN pokemon_types f ON f.species_id = p.species_id AND f.form_id = p.form_id
  LEFT JOIN pokemon_types s ON s.species_id = p.species_id AND s.form_id IS NULL
  CROSS JOIN LATERAL unnest(COALESCE(f.types, s.types)) AS t(type)
  GROUP BY 1, 2, 3
),
