  SELECT t.content_version_id, t.id, jsonb_agg(a.type ORDER BY a.ord) AS types
  FROM (
    SELECT DISTINCT tt.content_version_id, tt.id, weak.type
    FROM top_types tt
    JOIN type_weaknesses w ON w.type = tt.type
    CROSS JOIN LATERAL jsonb_array_elements_text(w.weaknesses) AS weak(type)
  ) t
  JOIN type_weaknesses a ON a.type = t.type
