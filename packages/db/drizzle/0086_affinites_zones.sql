  SELECT content_version_id, id, type FROM (
    SELECT content_version_id, id, type,
      rank() OVER (PARTITION BY content_version_id, id ORDER BY n DESC, weight DESC) AS rk
    FROM type_stats
  ) ranked
  WHERE rk = 1
),
